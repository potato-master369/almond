#ifndef DISK_PART_H
#define DISK_PART_H
#include "../../kernel_types.h"

// defines
#define PART_MAX_OPEN 1024

// modes
//  - A_FILE
//  - A_DIR
//  - A_OTHER // nfs, other stuff
// returned by some sort of stat

typedef enum {
  A_FILE,
  A_DIR,
  A_OTHER
} almond_filetype_t;

// rmods
// - r, w, rw, a, r+, w+, a+

// almond_filehandle_t open(path, mode, rmode)
// File handle
typedef struct {
  uint32_t id; // ID of filehandle - generated by kernel; unq
  uint32_t fsid; // ID of filesystem - disk X + partition Y in some sort of bit arrangement prob low 16 + hi 16
  uint32_t resv;
  uint16_t generation_count; // arbitrary; handled by driver not kernel
  uint64_t pos; // POSIX-style cursor of file
  uint32_t inode_n;
} almond_filehandle_t;

// these are indexed from the filehandle
typedef struct {
  uint32_t fsid;
  char name[256];
} almond_dirent_t;

// stat info
typedef struct {
  almond_filetype_t type;
  bool_t r; // applies to the current user
  bool_t w;
  bool_t x;
  uint32_t size;
  uint32_t inode_n;
  uint32_t fsid;
} almond_stat_t;

// user-facing pointer; to id
typedef uint32_t FILE;

// POSIX junk cos i couldnt invent a name
#define EPERM -1
#define ENOENT -2
#define EIO -3
#define EISDIR -4 // reuse for when a file is placed into kdir_* functions
#define EVFLOW -5
#define ENOMEM -6 // used to denote when kernel runs out of alloc space or whatnot
#define EINVAL -7

int kopen(almond_filehandle_t *out, const char *path, const char *mode); // in this case mode refers to rmods
int kclose(almond_filehandle_t *fh);
int kread(almond_filehandle_t *fh, void *buf, uint32_t count);
int kwrite(almond_filehandle_t *fh, const void *buf, uint32_t count);
int klseek(almond_filehandle_t *fh, uint64_t offset, int whence);
int kstat(almond_stat_t *out, const char *path); // returns 0 on success else the errors
int kdir_index(almond_filehandle_t *dir, uint32_t index, almond_dirent_t *out);
int kdir_count(almond_filehandle_t *dir, uint32_t *out);
#endif
